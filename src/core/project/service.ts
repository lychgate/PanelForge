// PanelForge — project folder format (S1.1).
//
// Defines the on-disk layout of a PanelForge project, its version marker,
// and the minimal initial metadata, per spec §7.1/§7.2 and the approved
// D5 resolution (owner, 2026-11-05):
//
// - database/project.db is the AUTHORITATIVE operational store (S1.2).
// - project.json at the project root is the version marker + minimal
//   manifest (format version + project ID) — enough to identify and
//   version-check a project without opening the database.
// - JSON files inside the project (e.g. characters/*/profile.json) are
//   optional human-readable mirrors regenerated by Core Engine export;
//   on conflict the database wins (see S1.5/S1.7).
//
// Stored paths are always relative to the project root with `/`
// separators (D7); resolveProjectPath() enforces it and rejects escapes.

import * as crypto from "crypto";
import * as fs from "fs";
import * as path from "path";

export const PROJECT_FORMAT_VERSION = 1;
export const PROJECT_MARKER_FILE = "project.json";
export const PROJECT_DATABASE_DIR = "database";
export const PROJECT_DATABASE_FILE = "project.db";

// Full directory tree per spec §7.1 (exemplary — may evolve, must stay
// understandable and portable). Nested entries imply their parents.
export const PROJECT_DIRECTORIES: readonly string[] = [
  "database",
  "manuscripts/original",
  "manuscripts/processed",
  "characters",
  "locations",
  "objects",
  "styles",
  "storyboards",
  "artwork/generated",
  "artwork/approved",
  "layouts",
  "exports",
  "workflows",
  "backups",
  "logs",
];

export type ProjectMetadata = {
  formatVersion: number;
  projectId: string;
  createdAt: string;
};

export type IdentifyResult =
  | { ok: true; metadata: ProjectMetadata }
  | { ok: false; code: "NOT_A_PROJECT" | "UNSUPPORTED_VERSION" | "CORRUPT_MARKER"; message: string };

function markerPathFor(root: string): string {
  return path.join(root, PROJECT_MARKER_FILE);
}

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

export function creationContract(): ProjectMetadata {
  return {
    formatVersion: PROJECT_FORMAT_VERSION,
    projectId: crypto.randomUUID(),
    createdAt: new Date().toISOString(),
  };
}

export function validateMetadata(raw: unknown): ProjectMetadata | null {
  if (!isPlainObject(raw)) return null;
  if (typeof raw.formatVersion !== "number" || !Number.isInteger(raw.formatVersion)) return null;
  if (typeof raw.projectId !== "string" || raw.projectId.trim() === "") return null;
  if (typeof raw.createdAt !== "string") return null;
  return {
    formatVersion: raw.formatVersion,
    projectId: raw.projectId,
    createdAt: raw.createdAt,
  };
}

/** Create the folder tree + version marker at root; returns the metadata. */
export function createProject(root: string, opts: { projectId?: string } = {}): ProjectMetadata {
  fs.mkdirSync(root, { recursive: true });
  for (const dir of PROJECT_DIRECTORIES) {
    fs.mkdirSync(path.join(root, dir), { recursive: true });
  }
  const metadata: ProjectMetadata = {
    ...creationContract(),
    ...(opts.projectId ? { projectId: opts.projectId } : {}),
  };
  writeMarker(root, metadata);
  return metadata;
}

function writeMarker(root: string, metadata: ProjectMetadata): void {
  const markerPath = markerPathFor(root);
  const tmpPath = `${markerPath}.tmp-${process.pid}-${Date.now()}`;
  fs.writeFileSync(tmpPath, JSON.stringify(metadata, null, 2) + "\n", {
    encoding: "utf8",
    mode: 0o600,
  });
  fs.renameSync(tmpPath, markerPath);
}

/** Identify a project at root and version-check its marker (no DB access). */
export function identifyProject(root: string): IdentifyResult {
  const normalized = path.resolve(root);
  if (!fs.existsSync(normalized) || !fs.statSync(normalized).isDirectory()) {
    return { ok: false, code: "NOT_A_PROJECT", message: "Project directory does not exist" };
  }
  const markerPath = markerPathFor(normalized);
  if (!fs.existsSync(markerPath)) {
    return { ok: false, code: "NOT_A_PROJECT", message: "No version marker (project.json) found" };
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(fs.readFileSync(markerPath, "utf8")) as unknown;
  } catch {
    return { ok: false, code: "CORRUPT_MARKER", message: "Version marker is not valid JSON" };
  }
  const metadata = validateMetadata(parsed);
  if (!metadata) {
    return { ok: false, code: "CORRUPT_MARKER", message: "Version marker has unexpected fields" };
  }
  if (metadata.formatVersion > PROJECT_FORMAT_VERSION) {
    return {
      ok: false,
      code: "UNSUPPORTED_VERSION",
      message: `Format version ${metadata.formatVersion} is newer than supported ${PROJECT_FORMAT_VERSION}; upgrade PanelForge`,
    };
  }
  return { ok: true, metadata };
}

/**
 * Resolve a stored project-relative path (canonical `/` separators, D7)
 * against the project root. Throws on absolute paths or traversal escapes.
 */
export function resolveProjectPath(root: string, relative: string): string {
  if (path.isAbsolute(relative)) {
    throw new Error("Project path must be relative to the project root");
  }
  const base = path.resolve(root);
  const joined = path.resolve(base, relative);
  if (joined !== base && !joined.startsWith(base + path.sep)) {
    throw new Error("Project path escapes the project directory");
  }
  return joined;
}
